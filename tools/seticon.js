const ResEdit=require('resedit'),fs=require('fs');
const [exe,ico]=process.argv.slice(2);
const data=fs.readFileSync(exe);const res=ResEdit.NtExecutableResource.from(ResEdit.NtExecutable.from(data,{ignoreCert:true}));
const exeObj=ResEdit.NtExecutable.from(data,{ignoreCert:true});const r=ResEdit.NtExecutableResource.from(exeObj);
const iconFile=ResEdit.Data.IconFile.from(fs.readFileSync(ico));
ResEdit.Resource.IconGroupEntry.replaceIconsForResource(r.entries,1,1033,iconFile.icons.map(i=>i.data));
const vi=ResEdit.Resource.VersionInfo.fromEntries(r.entries)[0];
vi.setStringValues({lang:1033,codepage:1200},{ProductName:'PokeOpening',FileDescription:'PokeOpening',CompanyName:'PokeOpening',OriginalFilename:'PokeOpening.exe',InternalName:'PokeOpening'});
vi.setFileVersion(1,0,0,0,1033);vi.setProductVersion(1,0,0,0,1033);vi.outputToResourceEntries(r.entries);
r.outputResource(exeObj);fs.writeFileSync(exe,Buffer.from(exeObj.generate()));console.log('icon ok');
